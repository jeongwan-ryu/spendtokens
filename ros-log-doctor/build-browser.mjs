import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
export async function browserSource(){
 const files=['dist/analyzer.js','src/view-model.js','src/app.js'];const parts=[];
 for(const file of files){const source=await readFile(new URL(file,import.meta.url),'utf8');parts.push(source.replace(/^import .+;\r?\n/gm,'').replace(/^export /gm,''));}
 return '// Generated by build-browser.mjs. Edit src/app.js, src/view-model.js and dist/analyzer.js.\n(function(){\n"use strict";\n'+parts.join('\n')+'\n})();\n';
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const source=await browserSource();const target=new URL('dist/app.js',import.meta.url);
 if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==source)throw Error('dist/app.js is stale. Run npm run build.');console.log('Browser bundle is current');}
 else{await writeFile(target,source);console.log('Browser bundle built; file:// support retained');}
}
